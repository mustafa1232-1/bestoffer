const activitySet = new Set(JOB_ACTIVITY_TYPES);
const departmentSet = new Set(
  Object.values(JOB_DEPARTMENTS_BY_ACTIVITY).flatMap((items) => items)
);

export function isKnownActivityType(activityType) {
  return activitySet.has(activityType);
}

export function isKnownDepartment(department) {
  return departmentSet.has(department);
}

export function isDepartmentAllowedForActivity(activityType, department) {
  const allowed = JOB_DEPARTMENTS_BY_ACTIVITY[activityType];
  if (!Array.isArray(allowed)) return false;
  return allowed.includes(department);
}

