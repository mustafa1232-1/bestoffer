/** Picks the guide entries most relevant to a question. */
export function findGuide(query, { limit = 3 } = {}) {
  const q = String(query || "").toLowerCase();
  // Describing a problem? Prefer the troubleshooting entries.
  const isProblem = /(ما يشتغل|ما يفتح|ما توصل|ما يوصل|مشكلة|خلل|عطل|يعلگ|يعلق|ما اگدر|ما أگدر|not working|doesn't|can't|problem)/i.test(q);
  const scored = APP_GUIDE.map((g) => ({
    g,
    score:
      g.keys.reduce((s, k) => (q.includes(k.toLowerCase()) ? s + k.length : s), 0) +
      (q.includes(g.topic) ? 2 : 0) +
      (isProblem && g.topic === "troubleshooting" ? 6 : 0),
  }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
  return scored.map(({ g }) => ({ id: g.id, topic: g.topic, how: g.text }));
}
