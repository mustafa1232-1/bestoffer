import {
  normalizeRiskLevel,
  normalizeSeverity,
} from "./types.js";

function toLowerText(value) {
  return String(value || "").trim().toLowerCase();
}

function inferSeverity(text) {
  if (
    text.includes("sev1") ||
    text.includes("critical") ||
    text.includes("database down") ||
    text.includes("payment failed") ||
    text.includes("fatal")
  ) {
    return "SEV1";
  }
  if (
    text.includes("sev2") ||
    text.includes("major") ||
    text.includes("error rate") ||
    text.includes("timeout") ||
    text.includes("latency")
  ) {
    return "SEV2";
  }
  if (
    text.includes("sev4") ||
    text.includes("warning") ||
    text.includes("notice")
  ) {
    return "SEV4";
  }
  return "SEV3";
}

function inferRisk(severity, text) {
  const sev = normalizeSeverity(severity, "SEV3");
  if (sev === "SEV1") return "critical";

  const sensitiveTokens = [
    "payment",
    "wallet",
    "settlement",
    "refund",
    "commission",
    "database",
    "migration",
    "auth",
    "authorization",
    "permission",
    "secret",
    "production",
  ];

  if (sensitiveTokens.some((token) => text.includes(token))) {
    return sev === "SEV2" ? "high" : "critical";
  }

  if (sev === "SEV2") return "high";
  if (sev === "SEV3") return "medium";
  return "low";
}

function inferModule(text, source) {
  const normalizedSource = toLowerText(source);
  const dictionary = [
    ["payment", "payments"],
    ["wallet", "wallets"],
    ["settlement", "settlements"],
    ["order", "orders"],
    ["taxi", "taxi"],
    ["driver", "delivery"],
    ["merchant", "merchants"],
    ["notification", "notifications"],
    ["database", "database"],
    ["auth", "authentication"],
    ["social", "social"],
    ["build", "ci_cd"],
    ["deploy", "deployment"],
  ];

  for (const [token, moduleName] of dictionary) {
    if (text.includes(token) || normalizedSource.includes(token)) {
      return moduleName;
    }
  }

  if (normalizedSource.includes("sentry")) return "application";
  if (normalizedSource.includes("datadog")) return "infrastructure";
  if (normalizedSource.includes("railway")) return "platform";
  if (normalizedSource.includes("github")) return "ci_cd";
  return "general";
}

function inferService(source, payload = {}) {
  const normalizedSource = toLowerText(source);
  if (normalizedSource.includes("sentry")) return "flutter_app";
  if (normalizedSource.includes("datadog")) return "backend_api";
  if (normalizedSource.includes("railway")) return "railway_service";
  if (normalizedSource.includes("github")) return "github_actions";
  if (payload?.service) return String(payload.service);
  return "maslaki";
}

